using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Orblit.Codegen;

/// <summary>
/// Finds types marked <c>[OrblitComponent]</c> and writes their registration, typed column access and
/// the manifest. A declaration it cannot read is an error and nothing is written: a component that does
/// not generate is better than one that generates wrongly and is found across a network session.
/// </summary>
[Generator]
public sealed class ComponentGenerator : IIncrementalGenerator
{
    // Internal to each assembly, so two assemblies that use the generator do not clash over it.
    private const string AttributeSource = """
        // <auto-generated/>
        #nullable enable
        namespace Orblit;

        /// <summary>Marks a type as a component. Every field must have the same type.</summary>
        [global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct, Inherited = false)]
        internal sealed class OrblitComponentAttribute : global::System.Attribute
        {
            /// <summary>The name both ends of a network session agree on. Defaults to the type name.</summary>
            public string? Name { get; set; }

            /// <summary>Overrides the storage inferred from the field types.</summary>
            public global::Orblit.Core.ComponentKind Kind { get; set; }

            /// <summary>Whether this component takes part in network replication.</summary>
            public bool Replicated { get; set; }

            /// <summary>Whether the client owning an entity may write this component. Meaningless unless replicated.</summary>
            public bool OwnerWritable { get; set; }
        }
        """;

    private static readonly DiagnosticDescriptor Refused = new(
        "ORBLIT001",
        "Component refused",
        "{0}",
        "Orblit",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(output => output.AddSource("OrblitComponentAttribute.g.cs", AttributeSource));

        var scans = context.SyntaxProvider.ForAttributeWithMetadataName(
            ComponentScanner.AttributeName,
            static (node, _) => node is TypeDeclarationSyntax,
            static (found, _) => ComponentScanner.ScanType(
                (INamedTypeSymbol)found.TargetSymbol,
                found.Attributes[0],
                found.TargetNode.SyntaxTree.FilePath));
        var assembly = context.CompilationProvider.Select(static (compilation, _) => compilation.AssemblyName ?? "Assembly");
        var projectDir = context.AnalyzerConfigOptionsProvider.Select(
            static (options, _) => options.GlobalOptions.TryGetValue("build_property.ProjectDir", out var dir) ? dir : "");

        context.RegisterSourceOutput(
            scans.Collect().Combine(assembly).Combine(projectDir),
            static (output, input) => Emit(output, input.Left.Left, input.Left.Right, input.Right));
    }

    private static void Emit(
        SourceProductionContext output,
        ImmutableArray<(ComponentDeclaration? Component, ComponentError? Error)> scans,
        string assembly,
        string projectDir)
    {
        var errors = scans.Where(s => s.Error is not null).Select(s => s.Error!).ToList();
        foreach (var error in errors)
        {
            output.ReportDiagnostic(Diagnostic.Create(Refused, Location.None, error.ToString()));
        }

        var found = scans.Where(s => s.Component is not null).Select(s => s.Component!).ToList();
        if (errors.Count > 0 || found.Count == 0)
        {
            return;
        }

        var components = new ScanResult(found.Select(c => c.At(ComponentScanner.Relative(projectDir, c.Source))), errors).Components;
        var code = ComponentEmitter.Registry(Names.Namespace(assembly), Names.Registry(assembly), assembly, components);
        output.AddSource("OrblitComponents.g.cs", SourceText.From(code, Encoding.UTF8));
    }
}
