using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Orblit.Json;

namespace Orblit.Codegen;

/// <summary>Writes registration code and a manifest from what the scanner found.</summary>
public static class ComponentEmitter
{
    /// <summary>The ComponentKind member and the C# element type each manifest kind maps to.</summary>
    private static readonly Dictionary<string, (string Member, string Element)> Kinds = new()
    {
        ["float32"] = ("Float32", "float"),
        ["float64"] = ("Float64", "double"),
        ["int32"] = ("Int32", "int"),
        ["uint32"] = ("UInt32", "uint"),
        ["int64"] = ("Int64", "long"),
        ["uint8"] = ("UInt8", "byte"),
    };

    /// <summary>
    /// The manifest other front ends read. The same bytes for the same
    /// components, so a tool can learn what a package declares without compiling it.
    /// </summary>
    public static string Manifest(string package, IReadOnlyList<ComponentDeclaration> components)
    {
        var builder = new StringBuilder("{\n  \"formatVersion\": 1,\n  \"package\": ");
        JsonQuote.Append(builder, package);
        builder.Append(",\n  \"components\": ");
        builder.Append(components.Count == 0 ? "[]" : "[\n" + string.Join(",\n", components.Select(Entry)) + "\n  ]");
        return builder.Append("\n}\n").ToString();
    }

    private static string Entry(ComponentDeclaration component)
    {
        var builder = new StringBuilder("    {\n      \"name\": ");
        JsonQuote.Append(builder, component.Name);
        builder.Append(",\n      \"class\": ");
        JsonQuote.Append(builder, component.TypeName);
        builder.Append(",\n      \"kind\": ");
        JsonQuote.Append(builder, component.Kind);
        builder.Append(",\n      \"arity\": ").Append(component.Arity);
        builder.Append(",\n      \"fields\": ").Append(Strings(component.Fields));
        builder.Append(",\n      \"replicated\": ").Append(Bool(component.Replicated));
        if (component.Replicated)
        {
            builder.Append(",\n      \"ownerWritable\": ").Append(Bool(component.OwnerWritable));
        }

        builder.Append(",\n      \"source\": ");
        JsonQuote.Append(builder, component.Source);
        return builder.Append("\n    }").ToString();
    }

    private static string Bool(bool value) => value ? "true" : "false";

    private static string Strings(IReadOnlyList<string> values)
    {
        if (values.Count == 0)
        {
            return "[]";
        }

        var builder = new StringBuilder("[\n");
        for (var i = 0; i < values.Count; i++)
        {
            builder.Append("        ");
            JsonQuote.Append(builder, values[i]);
            builder.Append(i == values.Count - 1 ? "\n" : ",\n");
        }

        return builder.Append("      ]").ToString();
    }

    /// <summary>Registration and typed column access, with the manifest alongside as a constant.</summary>
    public static string Registry(string @namespace, string className, string package, IReadOnlyList<ComponentDeclaration> components)
    {
        var builder = new StringBuilder();
        Line(builder, "// <auto-generated/>");
        Line(builder, "// GENERATED by Orblit.Codegen. Do not edit.");
        Line(builder, "//");
        Line(builder, "// Registering by hand means writing a name, a kind and an arity that have to agree with");
        Line(builder, "// the type and with whatever the other end of a network session registered. Generating");
        Line(builder, "// it removes that whole class of mismatch.");
        Line(builder, "#nullable enable");
        Line(builder);
        Line(builder, "using System;");
        Line(builder, "using System.Collections.Generic;");
        Line(builder, "using Orblit.Core;");
        Line(builder);
        Line(builder, $"namespace {@namespace};");
        Line(builder);
        WriteRegistry(builder, className, package, components);
        foreach (var component in components)
        {
            WriteColumn(builder, component);
        }

        return builder.ToString();
    }

    private static void Line(StringBuilder builder, string text = "") => builder.Append(text).Append('\n');

    private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

    private static string Collection(IEnumerable<ComponentDeclaration> components) =>
        "[" + string.Join(", ", components.Select(c => c.TypeName)) + "]";

    private static void WriteRegistry(StringBuilder builder, string className, string package, IReadOnlyList<ComponentDeclaration> all)
    {
        Line(builder, "/// <summary>");
        Line(builder, "/// Every component this assembly declares, against one world. Registration is idempotent, so two");
        Line(builder, "/// assemblies declaring the same component with the same layout resolve to one id.");
        Line(builder, "/// </summary>");
        Line(builder, $"public sealed class {className}");
        Line(builder, "{");
        Line(builder, $"    public {className}(World world)");
        Line(builder, "    {");
        foreach (var component in all)
        {
            var member = Kinds[component.Kind].Member;
            Line(builder, $"        {component.TypeName} = world.RegisterComponent({Literal(component.Name)}, ComponentKind.{member}, {component.Arity});");
        }

        Line(builder, "    }");
        Line(builder);
        foreach (var component in all)
        {
            Line(builder, $"    /// <summary>{component.TypeName}: {component.Kind} x{component.Arity} ({string.Join(", ", component.Fields)}).</summary>");
            Line(builder, $"    public ComponentType {component.TypeName} {{ get; }}");
            Line(builder);
        }

        var writable = all.Where(c => c.Replicated && c.OwnerWritable).Select(c => Literal(c.Name));
        Line(builder, "    /// <summary>Every declared component.</summary>");
        Line(builder, $"    public IReadOnlyList<ComponentType> All => {Collection(all)};");
        Line(builder);
        Line(builder, "    /// <summary>The components that cross the wire.</summary>");
        Line(builder, $"    public IReadOnlyList<ComponentType> Replicated => {Collection(all.Where(c => c.Replicated))};");
        Line(builder);
        Line(builder, "    /// <summary>Components an owning client may write, by registered name.</summary>");
        Line(builder, $"    public static IReadOnlySet<string> OwnerWritable {{ get; }} = new HashSet<string> {{ {string.Join(", ", writable)} }};");
        Line(builder);
        Line(builder, "    /// <summary>What <c>orblit_components.json</c> holds in a package. A generator cannot write a file.</summary>");
        Line(builder, $"    public const string Manifest = {Literal(Manifest(package, all))};");
        Line(builder, "}");
        Line(builder);
    }

    private static void WriteColumn(StringBuilder builder, ComponentDeclaration component)
    {
        var element = Kinds[component.Kind].Element;
        Line(builder, $"/// <summary>Typed access to a {component.TypeName} column.</summary>");
        Line(builder, "/// <remarks>A ref struct over the span, so this costs nothing at run time: the same memory with names on its offsets.</remarks>");
        Line(builder, $"public readonly ref struct {component.TypeName}Column");
        Line(builder, "{");
        // A primary constructor cannot capture a ref-like parameter, so the span gets a field.
        Line(builder, $"    private readonly Span<{element}> _data;");
        Line(builder);
        Line(builder, $"    public {component.TypeName}Column(Span<{element}> data) => _data = data;");
        Line(builder);
        Line(builder, "    /// <summary>How many entities the column holds.</summary>");
        Line(builder, $"    public int Length => _data.Length / {component.Arity};");
        for (var i = 0; i < component.Fields.Count; i++)
        {
            var field = component.Fields[i];
            var offset = i == 0 ? "" : $" + {i}";
            var setter = char.ToUpperInvariant(field[0]) + field.Substring(1);
            Line(builder);
            Line(builder, $"    public {element} {field}(int row) => _data[row * {component.Arity}{offset}];");
            Line(builder, $"    public void Set{setter}(int row, {element} value) => _data[row * {component.Arity}{offset}] = value;");
        }

        Line(builder, "}");
        Line(builder);
    }
}
